// Trip brief: a few plain sentences on what the result means, written by Claude when it is set up.

let tripBriefRequestId = 0;

// Shows the brief for the assessment on screen. Older responses are ignored if a newer one was requested.
async function renderTripBrief(assessment) {
  const container = document.querySelector("#trip-brief");
  if (!container) return;
  const requestId = ++tripBriefRequestId;
  container.className = "trip-brief loading";
  container.innerHTML = `
    <div class="trip-brief-head"><p class="trip-brief-label">Trip brief</p></div>
    <div class="trip-brief-skeleton"></div>
    <div class="trip-brief-skeleton short"></div>
  `;

  const { origin, destination, date, mode, originAirport, destinationAirport } = assessment.input;
  const params = new URLSearchParams({ origin, destination, date, mode, originAirport: originAirport || "", destinationAirport: destinationAirport || "" });
  try {
    const response = await fetch(`/api/analyze/brief?${params}`);
    const brief = await readJsonResponse(response, "Unable to write the trip brief");
    if (!response.ok) throw new Error(brief.error || "Unable to write the trip brief");
    if (requestId !== tripBriefRequestId) return;

    const byClaude = brief.source === "claude";
    container.className = `trip-brief ${byClaude ? "claude" : "template"}`;
    container.innerHTML = `
      <div class="trip-brief-head">
        <p class="trip-brief-label">Trip brief</p>
        <span class="trip-brief-tag"></span>
      </div>
      <p class="trip-brief-text"></p>
    `;
    const tag = container.querySelector(".trip-brief-tag");
    tag.textContent = byClaude ? "✦ Written by Claude" : "Built-in summary";
    tag.title = byClaude ? `Generated by ${brief.model} from the facts on this page` : brief.note || "";
    container.querySelector(".trip-brief-text").textContent = brief.text;
  } catch {
    if (requestId === tripBriefRequestId) container.classList.add("hidden");
  }
}
