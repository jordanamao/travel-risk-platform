-- Transactional outbox for risk-change alerts. A row is written in the same database transaction
-- as the trip_notifications row it announces, then a relay sends it to email or Slack and marks it.
create table alert_outbox (
  id bigint generated by default as identity primary key,
  dedupe_key varchar(255) not null,
  notification_id bigint not null,
  channel varchar(40) not null,
  payload varchar(4000) not null,
  status varchar(20) not null,
  attempts integer not null,
  next_attempt_at timestamp with time zone not null,
  last_error varchar(1000),
  created_at timestamp with time zone not null,
  sent_at timestamp with time zone,
  constraint uk_alert_outbox_dedupe_key unique (dedupe_key)
);

create index idx_alert_outbox_due on alert_outbox (status, next_attempt_at);
